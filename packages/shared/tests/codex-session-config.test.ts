describe('validateSlugForToml', () => {
  it('accepts valid slugs', () => {
    expect(validateSlugForToml('my-source')).toBe('my-source');
    expect(validateSlugForToml('github')).toBe('github');
    expect(validateSlugForToml('my-api-2')).toBe('my-api-2');
    expect(validateSlugForToml('a')).toBe('a');
  });

  it('rejects slugs with dots (TOML nested table injection)', () => {
    expect(() => validateSlugForToml('my.source')).toThrow('dangerous characters');
  });

  it('rejects slugs with brackets (TOML syntax injection)', () => {
    expect(() => validateSlugForToml('my[source]')).toThrow('dangerous characters');
  });

  it('rejects slugs with quotes', () => {
    expect(() => validateSlugForToml('my"source')).toThrow('dangerous characters');
  });

  it('rejects slugs with spaces', () => {
    expect(() => validateSlugForToml('my source')).toThrow('dangerous characters');
  });

  it('rejects slugs that start with hyphens', () => {
    expect(() => validateSlugForToml('-my-source')).toThrow('does not match expected pattern');
  });

  it('rejects slugs that end with hyphens', () => {
    expect(() => validateSlugForToml('my-source-')).toThrow('does not match expected pattern');
  });
});

