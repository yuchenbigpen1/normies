// ============================================================
// Test helpers
// ============================================================

function createMockSource(overrides: Partial<LoadedSource['config']> & { slug: string }): LoadedSource {
  return {
    config: {
      slug: overrides.slug,
      name: overrides.name || `Test Source ${overrides.slug}`,
      type: overrides.type || 'mcp',
      enabled: overrides.enabled !== undefined ? overrides.enabled : true,
      isAuthenticated: true,
      ...overrides,
    } as any,
    guide: null,
    folderPath: `/tmp/sources/${overrides.slug}`,
    workspaceRootPath: '/tmp/workspace',
    workspaceId: 'test-workspace',
  };
}

function createStdioMcpConfig(command: string, args?: string[]): SdkMcpServerConfig {
  return { type: 'stdio', command, args };
}

function createHttpMcpConfig(url: string, headers?: Record<string, string>): SdkMcpServerConfig {
  return { type: 'http', url, headers };
}

let testDir: string;

function createTestDir(): string {
  const dir = join(tmpdir(), `codex-config-test-${Date.now()}-${Math.random().toString(36).slice(2)}`);
  mkdirSync(dir, { recursive: true });
  return dir;
}

