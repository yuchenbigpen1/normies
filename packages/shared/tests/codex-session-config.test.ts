describe('generateCodexConfig', () => {
  it('generates header and sandbox section with no sources', () => {
    const result = generateCodexConfig({ sources: [] });
    expect(result.toml).toContain('# Generated by Normies');
    expect(result.toml).toContain('sandbox_mode = "danger-full-access"');
    expect(result.mcpSources).toEqual([]);
    expect(result.apiSources).toEqual([]);
    expect(result.warnings).toEqual([]);
  });

  it('generates MCP server section for stdio source', () => {
    const source = createMockSource({ slug: 'my-db', type: 'mcp' });
    const mcpServerConfigs: Record<string, SdkMcpServerConfig> = {
      'my-db': createStdioMcpConfig('/usr/bin/mcp-db', ['--port', '5432']),
    };

    const result = generateCodexConfig({ sources: [source], mcpServerConfigs });

    expect(result.toml).toContain('[mcp_servers.my-db]');
    expect(result.toml).toContain('command = "/usr/bin/mcp-db"');
    expect(result.toml).toContain('args = ["--port", "5432"]');
    expect(result.mcpSources).toEqual(['my-db']);
    expect(result.warnings).toEqual([]);
  });

  it('generates MCP server section for HTTP source', () => {
    const source = createMockSource({ slug: 'remote-api', type: 'mcp' });
    const mcpServerConfigs: Record<string, SdkMcpServerConfig> = {
      'remote-api': createHttpMcpConfig('https://mcp.example.com', { 'Authorization': 'Bearer token123' }),
    };

    const result = generateCodexConfig({ sources: [source], mcpServerConfigs });

    expect(result.toml).toContain('[mcp_servers.remote-api]');
    expect(result.toml).toContain('url = "https://mcp.example.com"');
    expect(result.toml).toContain('http_headers');
    expect(result.mcpSources).toEqual(['remote-api']);
  });

  it('skips disabled sources', () => {
    const source = createMockSource({ slug: 'disabled-one', type: 'mcp', enabled: false });
    const mcpServerConfigs: Record<string, SdkMcpServerConfig> = {
      'disabled-one': createStdioMcpConfig('/usr/bin/mcp'),
    };

    const result = generateCodexConfig({ sources: [source], mcpServerConfigs });

    expect(result.toml).not.toContain('[mcp_servers.disabled-one]');
    expect(result.mcpSources).toEqual([]);
  });

  it('warns when MCP source has no server config', () => {
    const source = createMockSource({ slug: 'no-config', type: 'mcp' });

    const result = generateCodexConfig({ sources: [source], mcpServerConfigs: {} });

    expect(result.warnings).toHaveLength(1);
    expect(result.warnings[0].type).toBe('missing_server_config');
    expect(result.warnings[0].sourceSlug).toBe('no-config');
    expect(result.mcpSources).toEqual([]);
  });

  it('warns when slug validation fails', () => {
    // Create a source with a slug that passes the filter but fails TOML validation
    const source = createMockSource({ slug: 'bad.slug', type: 'mcp' });
    const mcpServerConfigs: Record<string, SdkMcpServerConfig> = {
      'bad.slug': createStdioMcpConfig('/usr/bin/mcp'),
    };

    const result = generateCodexConfig({ sources: [source], mcpServerConfigs });

    expect(result.warnings).toHaveLength(1);
    expect(result.warnings[0].type).toBe('slug_validation_failed');
  });

  it('tracks API sources and warns when bridge not configured', () => {
    const source = createMockSource({ slug: 'stripe', type: 'api' as any });

    const result = generateCodexConfig({ sources: [source] });

    expect(result.apiSources).toEqual(['stripe']);
    expect(result.warnings).toHaveLength(1);
    expect(result.warnings[0].type).toBe('bridge_not_configured');
    expect(result.needsBridge).toBe(false);
  });

  it('includes bridge server section when API sources and bridge are configured', () => {
    const source = createMockSource({ slug: 'stripe', type: 'api' as any });

    const result = generateCodexConfig({
      sources: [source],
      bridgeServerPath: '/path/to/bridge.js',
      bridgeConfigPath: '/path/to/bridge-config.json',
      nodePath: '/usr/local/bin/node',
    });

    expect(result.toml).toContain('[mcp_servers.api-bridge]');
    expect(result.toml).toContain('command = "/usr/local/bin/node"');
    expect(result.needsBridge).toBe(true);
    expect(result.apiSources).toEqual(['stripe']);
    expect(result.warnings).toEqual([]);
  });

  it('includes session server section when all params provided', () => {
    const result = generateCodexConfig({
      sources: [],
      sessionServerPath: '/path/to/session-server.js',
      sessionId: 'sess-123',
      workspaceRootPath: '/workspace',
      plansFolderPath: '/workspace/sessions/sess-123/plans',
      nodePath: '/usr/bin/node',
    });

    expect(result.toml).toContain('[mcp_servers.session]');
    expect(result.toml).toContain('command = "/usr/bin/node"');
    expect(result.toml).toContain('"--session-id", "sess-123"');
  });

  it('skips session server section when params are missing', () => {
    const result = generateCodexConfig({
      sources: [],
      sessionServerPath: '/path/to/session-server.js',
      // Missing sessionId, workspaceRootPath, plansFolderPath
    });

    expect(result.toml).not.toContain('[mcp_servers.session]');
  });

  it('handles multiple MCP sources', () => {
    const sources = [
      createMockSource({ slug: 'github', type: 'mcp' }),
      createMockSource({ slug: 'linear', type: 'mcp' }),
      createMockSource({ slug: 'notion', type: 'mcp' }),
    ];
    const mcpServerConfigs: Record<string, SdkMcpServerConfig> = {
      'github': createStdioMcpConfig('/usr/bin/github-mcp'),
      'linear': createHttpMcpConfig('https://linear.mcp.dev'),
      'notion': createStdioMcpConfig('/usr/bin/notion-mcp', ['--key', 'abc']),
    };

    const result = generateCodexConfig({ sources, mcpServerConfigs });

    expect(result.mcpSources).toEqual(['github', 'linear', 'notion']);
    expect(result.toml).toContain('[mcp_servers.github]');
    expect(result.toml).toContain('[mcp_servers.linear]');
    expect(result.toml).toContain('[mcp_servers.notion]');
    expect(result.warnings).toEqual([]);
  });

  it('includes model provider section when configured', () => {
    const result = generateCodexConfig({
      sources: [],
      modelProvider: {
        id: 'openrouter',
        name: 'OpenRouter',
        baseUrl: 'https://openrouter.ai/api/v1',
        envKey: 'OPENROUTER_API_KEY',
        wireApi: 'chat',
        defaultModel: 'gpt-4',
      },
    });

    expect(result.toml).toContain('[model_providers.openrouter]');
    expect(result.toml).toContain('name = "OpenRouter"');
    expect(result.toml).toContain('base_url = "https://openrouter.ai/api/v1"');
    expect(result.toml).toContain('[profiles.openrouter]');
    expect(result.toml).toContain('model = "gpt-4"');
  });

  it('sets default timeout values', () => {
    const source = createMockSource({ slug: 'test', type: 'mcp' });
    const mcpServerConfigs: Record<string, SdkMcpServerConfig> = {
      'test': createStdioMcpConfig('/usr/bin/test'),
    };

    const result = generateCodexConfig({ sources: [source], mcpServerConfigs });

    expect(result.toml).toContain('startup_timeout_sec = 15');
    expect(result.toml).toContain('tool_timeout_sec = 120');
  });
});

