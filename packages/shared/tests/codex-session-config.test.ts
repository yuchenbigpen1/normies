describe('setupCodexSessionConfig', () => {
  beforeEach(() => {
    testDir = createTestDir();
  });

  afterEach(() => {
    if (testDir && existsSync(testDir)) {
      rmSync(testDir, { recursive: true, force: true });
    }
  });

  it('creates .codex-home directory and writes config.toml', () => {
    const result = setupCodexSessionConfig({
      sessionPath: testDir,
      sources: [],
      mcpServerConfigs: {},
    });

    const codexHome = join(testDir, '.codex-home');
    expect(existsSync(codexHome)).toBe(true);
    expect(existsSync(join(codexHome, 'config.toml'))).toBe(true);
    expect(result.codexHome).toBe(codexHome);
  });

  it('writes valid TOML with MCP sources', () => {
    const source = createMockSource({ slug: 'github', type: 'mcp' });
    const mcpServerConfigs: Record<string, SdkMcpServerConfig> = {
      'github': createStdioMcpConfig('/usr/bin/github-mcp', ['--token', 'abc']),
    };

    setupCodexSessionConfig({
      sessionPath: testDir,
      sources: [source],
      mcpServerConfigs,
    });

    const toml = readFileSync(join(testDir, '.codex-home', 'config.toml'), 'utf-8');
    expect(toml).toContain('[mcp_servers.github]');
    expect(toml).toContain('command = "/usr/bin/github-mcp"');
  });

  it('is safe to call multiple times (overwrites config)', () => {
    // First call with one source
    const source1 = createMockSource({ slug: 'source-a', type: 'mcp' });
    setupCodexSessionConfig({
      sessionPath: testDir,
      sources: [source1],
      mcpServerConfigs: {
        'source-a': createStdioMcpConfig('/usr/bin/a'),
      },
    });

    let toml = readFileSync(join(testDir, '.codex-home', 'config.toml'), 'utf-8');
    expect(toml).toContain('[mcp_servers.source-a]');

    // Second call with different source — should overwrite
    const source2 = createMockSource({ slug: 'source-b', type: 'mcp' });
    setupCodexSessionConfig({
      sessionPath: testDir,
      sources: [source2],
      mcpServerConfigs: {
        'source-b': createStdioMcpConfig('/usr/bin/b'),
      },
    });

    toml = readFileSync(join(testDir, '.codex-home', 'config.toml'), 'utf-8');
    expect(toml).toContain('[mcp_servers.source-b]');
    expect(toml).not.toContain('[mcp_servers.source-a]');
  });

  it('returns config result with source lists and warnings', () => {
    const source = createMockSource({ slug: 'missing-config', type: 'mcp' });

    const result = setupCodexSessionConfig({
      sessionPath: testDir,
      sources: [source],
      mcpServerConfigs: {},
    });

    expect(result.configResult.warnings).toHaveLength(1);
    expect(result.configResult.warnings[0].sourceSlug).toBe('missing-config');
  });

  it('passes session server config through to TOML', () => {
    setupCodexSessionConfig({
      sessionPath: testDir,
      sources: [],
      mcpServerConfigs: {},
      sessionServerPath: '/path/to/session-server.js',
      nodePath: '/usr/bin/node',
      sessionId: 'sess-abc',
      workspaceRootPath: '/workspace',
      plansFolderPath: '/workspace/sessions/sess-abc/plans',
    });

    const toml = readFileSync(join(testDir, '.codex-home', 'config.toml'), 'utf-8');
    expect(toml).toContain('[mcp_servers.session]');
    expect(toml).toContain('"--session-id", "sess-abc"');
  });
});
